import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split, cross_val_score, StratifiedKFold
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (classification_report, roc_auc_score,
                             average_precision_score, confusion_matrix)

# 1. Load data
df = pd.read_csv("orders.csv")
print("Rows:", len(df))
print(df.columns.tolist())

# 2. Target: anything that did not end up Delivered
y = (df["Order Status"] != "Delivered").astype(int)
print("Cancel/reject rate:", round(y.mean() * 100, 2), "%", f"({y.sum()} orders)")

# 3. Drop leakage - these are only known AFTER the order succeeds or fails
leak = [
    "Order Status",                                # the target itself
    "Cancellation / Rejection reason",             # only filled when it failed
    "Restaurant compensation (Cancellation)",
    "Restaurant penalty (Rejection)",
    "Rating", "Review", "Customer complaint tag",  # given after delivery
    "KPT duration (minutes)",                      # kitchen time, happens after
    "Rider wait time (minutes)",
    "Order Ready Marked",
]
ids = ["Order ID", "Customer ID", "Restaurant ID", "Delivery", "City"]  # ids / constants
X = df.drop(columns=leak + ids)

# 4. Order Placed At -> hour and weekday
t = pd.to_datetime(df["Order Placed At"], format="%I:%M %p, %B %d %Y", errors="coerce")
X["hour"] = t.dt.hour
X["day_of_week"] = t.dt.dayofweek
X["is_weekend"] = (t.dt.dayofweek >= 5).astype(int)
X["is_dinner"] = t.dt.hour.between(19, 22).astype(int)
X = X.drop(columns=["Order Placed At"])

# 5. Distance "3km" / "<1km" -> number
X["distance_km"] = (df["Distance"].str.replace("<1km", "0.5", regex=False)
                                  .str.replace("km", "", regex=False)
                                  .astype(float))
X = X.drop(columns=["Distance"])

# 6. Items in order -> how many items, how many units
items = df["Items in order"].fillna("")
X["n_item_types"] = items.str.count(",") + 1
X["n_units"] = items.str.findall(r"(\d+) x").apply(lambda l: sum(int(i) for i in l))
X = X.drop(columns=["Items in order"])

# 7. Instructions / discount -> simple flags
X["has_instructions"] = df["Instructions"].notna().astype(int)
X["has_discount"] = df["Discount construct"].notna().astype(int)
X = X.drop(columns=["Instructions"])

# 8. Money features
X["total_discount"] = (df["Restaurant discount (Promo)"]
                       + df["Restaurant discount (Flat offs, Freebies & others)"]
                       + df["Gold discount"] + df["Brand pack discount"])
X["discount_pct"] = X["total_discount"] / df["Bill subtotal"].replace(0, np.nan)

# 9. Text columns -> numbers, fill gaps
# "Discount construct" has 527 unique strings. One-hot encoding it makes 500+
# columns for only 190 cancellations, which just overfits - the flag is enough.
X = X.drop(columns=["Discount construct"])
X = pd.get_dummies(X, columns=["Restaurant name", "Subzone"], dummy_na=True)
X = X.fillna(X.median(numeric_only=True))
print("Features:", X.shape[1])

# 10. Split and train
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y)

model = RandomForestClassifier(n_estimators=300, min_samples_leaf=5,
                               class_weight="balanced", random_state=42, n_jobs=-1)
model.fit(X_train, y_train)

# 11. Evaluate - accuracy is useless here, look at ROC-AUC and PR-AUC
prob = model.predict_proba(X_test)[:, 1]
pred = (prob >= 0.5).astype(int)

base = y_test.mean()
print("\nROC-AUC :", round(roc_auc_score(y_test, prob), 4))
print("PR-AUC  :", round(average_precision_score(y_test, prob), 4),
      " (random guessing would score", round(base, 4), ")")
print("\nConfusion matrix:\n", confusion_matrix(y_test, pred))
print("\n", classification_report(y_test, pred, zero_division=0))

# 12. Cross-validation, because the test set has very few cancellations
cv = StratifiedKFold(5, shuffle=True, random_state=42)
scores = cross_val_score(model, X, y, cv=cv, scoring="roc_auc")
print("5-fold ROC-AUC:", scores.round(3), "mean", round(scores.mean(), 3))

# 13. Top features
imp = pd.Series(model.feature_importances_, index=X.columns)
print("\nTop features:\n", imp.sort_values(ascending=False).head(12))

